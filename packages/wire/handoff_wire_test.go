func TestEncodeControlManifestWithContentKind(t *testing.T) {
	m := NewManifest([]FileEntry{{
		Idx: 0, Name: "a.txt", Size: 5, Mime: "text/plain; charset=utf-8",
		LastModified: 5, BlockSize: 8, Blocks: 1, FileDigest: "ab",
	}}, 5)
	m.ContentKind = ContentKindText
	got, err := EncodeControl(m)
	if err != nil {
		t.Fatal(err)
	}
	want := `{"type":2,"contentKind":"text","files":[{"idx":0,"name":"a.txt","size":5,"mime":"text/plain; charset=utf-8","lastModified":5,"blockSize":8,"blocks":1,"fileDigest":"ab"}],"totalSize":5}`
	if string(got) != want {
		t.Fatalf("manifest bytes differ:\n got: %s\nwant: %s", got, want)
	}
}

func TestDecodeControlManifestPreservesContentKind(t *testing.T) {
	raw := `{"type":2,"contentKind":"link","files":[{"idx":0,"name":"link.txt","size":19,"mime":"text/plain; charset=utf-8","lastModified":5,"blockSize":32,"blocks":1,"fileDigest":"cd"}],"totalSize":19}`
	msg, err := DecodeControl([]byte(raw))
	if err != nil {
		t.Fatal(err)
	}
	m, ok := msg.(*Manifest)
	if !ok {
		t.Fatalf("decoded to %T, want *Manifest", msg)
	}
	if m.ContentKind != ContentKindLink {
		t.Fatalf("contentKind = %q, want %q", m.ContentKind, ContentKindLink)
	}
	if _, err := ValidateManifest(*m); err != nil {
		t.Fatalf("decoded manifest failed validation: %v", err)
	}
}

func TestManifestFingerprintCoversContentKind(t *testing.T) {
	a := NewManifest([]FileEntry{handoffEntry(9)}, 9)
	b := NewManifest([]FileEntry{handoffEntry(9)}, 9)
	b.ContentKind = ContentKindText
	fa, err := ManifestFingerprint(*a)
	if err != nil {
		t.Fatal(err)
	}
	fb, err := ManifestFingerprint(*b)
	if err != nil {
		t.Fatal(err)
	}
	if fa == fb {
		t.Fatal("fingerprint ignores contentKind: file and handoff manifests collide")
	}
}

