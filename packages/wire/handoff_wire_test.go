// V20-PR06: text/link handoffs ride the existing transfer protocol as a typed,
// size-bounded content envelope on the manifest. These are the wire-format
// regression tests: unknown kinds fail, handoffs must be exactly one small
// file, and the exact JSON byte layout must match the TypeScript twin.
func handoffEntry(size int64) FileEntry {
	const blockSize = int64(8)
	blocks := int64(0)
	if size > 0 {
		blocks = (size-1)/blockSize + 1
	}
	return FileEntry{Idx: 0, Name: "text.txt", Size: size, Mime: "text/plain; charset=utf-8",
		LastModified: 5, BlockSize: int(blockSize), Blocks: int(blocks), FileDigest: "ab"}
}

func TestValidateManifestRejectsUnknownContentKind(t *testing.T) {
	m := NewManifest([]FileEntry{handoffEntry(9)}, 9)
	m.ContentKind = "audio"
	if _, err := ValidateManifest(*m); err == nil {
		t.Fatal("ValidateManifest accepted unknown contentKind")
	}
}

func TestValidateManifestHandoffRequiresSingleFile(t *testing.T) {
	m := NewManifest([]FileEntry{handoffEntry(9), handoffEntry(9)}, 18)
	m.ContentKind = ContentKindText
	if _, err := ValidateManifest(*m); err == nil {
		t.Fatal("ValidateManifest accepted a multi-file text handoff")
	}
}

func TestValidateManifestHandoffSizeBounds(t *testing.T) {
	for _, tc := range []struct {
		name string
		size int64
		ok   bool
	}{
		{"zero bytes rejected", 0, false},
		{"one byte accepted", 1, true},
		{"cap accepted", MaxHandoffBytes, true},
		{"cap plus one rejected", MaxHandoffBytes + 1, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			m := NewManifest([]FileEntry{handoffEntry(tc.size)}, tc.size)
			m.ContentKind = ContentKindText
			_, err := ValidateManifest(*m)
			if tc.ok && err != nil {
				t.Fatalf("expected ok, got %v", err)
			}
			if !tc.ok && err == nil {
				t.Fatal("expected rejection, got ok")
			}
		})
	}
}

