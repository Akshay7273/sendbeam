// V20-PR06: exact wire bytes for a handoff manifest — pins Go/TS parity for the
// contentKind envelope (the same fixture is generated by the TS differential
// suite as ctrl_handoff_manifest_text).
func TestHandoffManifestExactBytes(t *testing.T) {
	m := &Manifest{
		Type:        FrameManifest,
		TransferID:  "handoff-text-00000000",
		ContentKind: ContentKindText,
		Files:       []FileEntry{{Idx: 0, Name: "text.txt", Size: 13, Mime: "text/plain; charset=utf-8", LastModified: 1700000000000, BlockSize: 65536, Blocks: 1, FileDigest: strings.Repeat("1", 64)}},
		TotalSize:   13,
	}
	enc, err := EncodeControl(*m)
	if err != nil {
		t.Fatal(err)
	}
	want := `{"type":2,"transferId":"handoff-text-00000000","contentKind":"text","files":[{"idx":0,"name":"text.txt","size":13,"mime":"text/plain; charset=utf-8","lastModified":1700000000000,"blockSize":65536,"blocks":1,"fileDigest":"` + strings.Repeat("1", 64) + `"}],"totalSize":13}`
	if string(enc) != want {
		t.Fatalf("handoff manifest bytes changed:\n got %s\nwant %s", enc, want)
	}
	// The round trip preserves the kind.
	dec, err := DecodeControl(enc)
	if err != nil {
		t.Fatal(err)
	}
	if dec.(*Manifest).ContentKind != ContentKindText {
		t.Fatal("decoded manifest lost contentKind")
	}
}

