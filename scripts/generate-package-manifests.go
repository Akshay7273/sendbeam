func generateAllManifests(outDir string, syncRoot bool, version, tag, repo, homepage, relDate string, hashes PackageHashes) error {
	// Homebrew formula
	brewFormula := generateHomebrewFormula(version, tag, repo, homepage, hashes)
	brewDir := filepath.Join(outDir, "homebrew", "Formula")
	if err := os.MkdirAll(brewDir, 0755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(brewDir, "sendbeam.rb"), []byte(brewFormula), 0644); err != nil {
		return err
	}
	if syncRoot {
		if err := os.MkdirAll("Formula", 0755); err != nil {
			return err
		}
		if err := os.WriteFile("Formula/sendbeam.rb", []byte(brewFormula), 0644); err != nil {
			return err
		}
	}

	// Scoop manifest
	scoopManifest, err := generateScoopManifest(version, tag, repo, homepage, hashes)
	if err != nil {
		return err
	}
	scoopDir := filepath.Join(outDir, "scoop")
	if err := os.MkdirAll(scoopDir, 0755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(scoopDir, "sendbeam.json"), []byte(scoopManifest), 0644); err != nil {
		return err
	}
	if syncRoot {
		if err := os.MkdirAll("bucket", 0755); err != nil {
			return err
		}
		if err := os.WriteFile("bucket/sendbeam.json", []byte(scoopManifest), 0644); err != nil {
			return err
		}
	}

	// WinGet manifests
	wingetVer := generateWinGetVersion(version)
	wingetInst := generateWinGetInstaller(version, tag, repo, relDate, hashes)
	wingetLoc := generateWinGetLocale(version, homepage, repo)

	wingetVersionDir := filepath.Join(outDir, "winget", "manifests", "s", "SendBeam", "SendBeam", version)
	if err := os.MkdirAll(wingetVersionDir, 0755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(wingetVersionDir, "SendBeam.SendBeam.yaml"), []byte(wingetVer), 0644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(wingetVersionDir, "SendBeam.SendBeam.installer.yaml"), []byte(wingetInst), 0644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(wingetVersionDir, "SendBeam.SendBeam.locale.en-US.yaml"), []byte(wingetLoc), 0644); err != nil {
		return err
	}

	// Top-level winget template
	wingetTopDir := filepath.Join(outDir, "winget")
	if err := os.WriteFile(filepath.Join(wingetTopDir, "SendBeam.SendBeam.yaml"), []byte(wingetVer), 0644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(wingetTopDir, "SendBeam.SendBeam.installer.yaml"), []byte(wingetInst), 0644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(wingetTopDir, "SendBeam.SendBeam.locale.en-US.yaml"), []byte(wingetLoc), 0644); err != nil {
		return err
	}

	// AUR PKGBUILD and .SRCINFO
	aurPKGBUILD := generateAURPKGBUILD(version, tag, repo, homepage, hashes)
	aurSRCINFO := generateAURSRCINFO(version, tag, repo, homepage, hashes)

	aurDir := filepath.Join(outDir, "aur")
	if err := os.MkdirAll(aurDir, 0755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(aurDir, "PKGBUILD"), []byte(aurPKGBUILD), 0644); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(aurDir, ".SRCINFO"), []byte(aurSRCINFO), 0644); err != nil {
		return err
	}

	return nil
}

func validateManifests(outDir string, syncRoot bool, version, tag, repo string, hashes PackageHashes) error {
	// Validate Homebrew
	brewPaths := []string{filepath.Join(outDir, "homebrew", "Formula", "sendbeam.rb")}
	if syncRoot {
		brewPaths = append(brewPaths, "Formula/sendbeam.rb")
	}
	for _, p := range brewPaths {
		data, err := os.ReadFile(p)
		if err != nil {
			return fmt.Errorf("reading brew formula %s: %w", p, err)
		}
		content := string(data)
		if !strings.Contains(content, fmt.Sprintf("version \"%s\"", version)) {
			return fmt.Errorf("%s: version does not match %s", p, version)
		}
		if !strings.Contains(content, hashes.DarwinArm64) {
			return fmt.Errorf("%s: missing darwin-arm64 hash %s", p, hashes.DarwinArm64)
		}
		if !strings.Contains(content, hashes.DarwinAmd64) {
			return fmt.Errorf("%s: missing darwin-amd64 hash %s", p, hashes.DarwinAmd64)
		}
		if !strings.Contains(content, hashes.LinuxArm64) {
			return fmt.Errorf("%s: missing linux-arm64 hash %s", p, hashes.LinuxArm64)
		}
		if !strings.Contains(content, hashes.LinuxAmd64) {
			return fmt.Errorf("%s: missing linux-amd64 hash %s", p, hashes.LinuxAmd64)
		}
	}

	// Validate Scoop
	scoopPaths := []string{filepath.Join(outDir, "scoop", "sendbeam.json")}
	if syncRoot {
		scoopPaths = append(scoopPaths, "bucket/sendbeam.json")
	}
	for _, p := range scoopPaths {
		data, err := os.ReadFile(p)
		if err != nil {
			return fmt.Errorf("reading scoop manifest %s: %w", p, err)
		}
		var manifest struct {
			Version      string `json:"version"`
			Architecture struct {
				Bit64 struct {
					URL  string `json:"url"`
					Hash string `json:"hash"`
				} `json:"64bit"`
				Arm64 struct {
					URL  string `json:"url"`
					Hash string `json:"hash"`
				} `json:"arm64"`
			} `json:"architecture"`
			Bin string `json:"bin"`
		}
		if err := json.Unmarshal(data, &manifest); err != nil {
			return fmt.Errorf("%s is invalid JSON: %w", p, err)
		}
		if manifest.Version != version {
			return fmt.Errorf("%s: expected version %s, got %s", p, version, manifest.Version)
		}
		if manifest.Architecture.Bit64.Hash != hashes.WindowsAmd64 {
			return fmt.Errorf("%s: 64bit hash mismatch (expected %s, got %s)", p, hashes.WindowsAmd64, manifest.Architecture.Bit64.Hash)
		}
		if manifest.Architecture.Arm64.Hash != hashes.WindowsArm64 {
			return fmt.Errorf("%s: arm64 hash mismatch (expected %s, got %s)", p, hashes.WindowsArm64, manifest.Architecture.Arm64.Hash)
		}
		if manifest.Bin != "sendbeam.exe" {
			return fmt.Errorf("%s: expected bin sendbeam.exe, got %s", p, manifest.Bin)
		}
	}

	// Validate WinGet
	wingetVersionPath := filepath.Join(outDir, "winget", "manifests", "s", "SendBeam", "SendBeam", version)
	wingetFiles := []string{
		filepath.Join(wingetVersionPath, "SendBeam.SendBeam.yaml"),
		filepath.Join(wingetVersionPath, "SendBeam.SendBeam.installer.yaml"),
		filepath.Join(wingetVersionPath, "SendBeam.SendBeam.locale.en-US.yaml"),
	}
	for _, f := range wingetFiles {
		data, err := os.ReadFile(f)
		if err != nil {
			return fmt.Errorf("reading winget file %s: %w", f, err)
		}
		content := string(data)
		if !strings.Contains(content, fmt.Sprintf("PackageVersion: %s", version)) {
			return fmt.Errorf("%s: missing PackageVersion %s", f, version)
		}
		if strings.HasSuffix(f, ".installer.yaml") {
			if !strings.Contains(content, strings.ToUpper(hashes.WindowsAmd64)) {
				return fmt.Errorf("%s: missing uppercase windows-amd64 hash %s", f, strings.ToUpper(hashes.WindowsAmd64))
			}
			if !strings.Contains(content, strings.ToUpper(hashes.WindowsArm64)) {
				return fmt.Errorf("%s: missing uppercase windows-arm64 hash %s", f, strings.ToUpper(hashes.WindowsArm64))
			}
		}
	}

	// Validate AUR
	aurPKGBUILDPath := filepath.Join(outDir, "aur", "PKGBUILD")
	aurData, err := os.ReadFile(aurPKGBUILDPath)
	if err != nil {
		return fmt.Errorf("reading AUR PKGBUILD %s: %w", aurPKGBUILDPath, err)
	}
	aurContent := string(aurData)
	if !strings.Contains(aurContent, fmt.Sprintf("pkgver=%s", version)) {
		return fmt.Errorf("%s: missing pkgver=%s", aurPKGBUILDPath, version)
	}
	if !strings.Contains(aurContent, hashes.LinuxAmd64) {
		return fmt.Errorf("%s: missing x86_64 hash %s", aurPKGBUILDPath, hashes.LinuxAmd64)
	}
	if !strings.Contains(aurContent, hashes.LinuxArm64) {
		return fmt.Errorf("%s: missing aarch64 hash %s", aurPKGBUILDPath, hashes.LinuxArm64)
	}

	aurSRCINFOPath := filepath.Join(outDir, "aur", ".SRCINFO")
	srcinfoData, err := os.ReadFile(aurSRCINFOPath)
	if err != nil {
		return fmt.Errorf("reading AUR .SRCINFO %s: %w", aurSRCINFOPath, err)
	}
	srcinfoContent := string(srcinfoData)
	pkgverRe := regexp.MustCompile(`\bpkgver\s*=\s*` + regexp.QuoteMeta(version))
	if !pkgverRe.MatchString(srcinfoContent) {
		return fmt.Errorf("%s: missing pkgver = %s", aurSRCINFOPath, version)
	}
	if !strings.Contains(srcinfoContent, hashes.LinuxAmd64) {
		return fmt.Errorf("%s: missing x86_64 hash %s", aurSRCINFOPath, hashes.LinuxAmd64)
	}
	if !strings.Contains(srcinfoContent, hashes.LinuxArm64) {
		return fmt.Errorf("%s: missing aarch64 hash %s", aurSRCINFOPath, hashes.LinuxArm64)
	}

	return nil
}
