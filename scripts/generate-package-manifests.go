type PackageHashes struct {
	DarwinArm64  string
	DarwinAmd64  string
	LinuxArm64   string
	LinuxAmd64   string
	WindowsArm64 string
	WindowsAmd64 string
}

func main() {
	var (
		versionFlag  = flag.String("version", "", "product version (e.g. 1.7.0)")
		tagFlag      = flag.String("tag", "", "release tag (e.g. v1.7.0)")
		sumsFlag     = flag.String("sums", "SHA256SUMS.txt", "path to SHA256SUMS.txt manifest")
		repoFlag     = flag.String("repo", "Akshay7273/sendbeam", "GitHub repository owner/name")
		homepageFlag = flag.String("homepage", "https://omnitrix.space", "product homepage URL")
		outDirFlag   = flag.String("out-dir", "packaging", "output directory for packaging manifests")
		syncRootFlag = flag.Bool("sync-root", true, "sync Formula/sendbeam.rb and bucket/sendbeam.json at repo root")
		validateFlag = flag.Bool("validate", false, "validate existing manifests against SHA256SUMS.txt without writing")
		dateFlag     = flag.String("release-date", "", "release date in YYYY-MM-DD format (defaults to current UTC date)")
	)
	flag.Parse()

	if *versionFlag == "" && *tagFlag == "" {
		fmt.Fprintf(os.Stderr, "error: either --version or --tag is required\n")
		os.Exit(1)
	}

	version := *versionFlag
	tag := *tagFlag
	if version == "" {
		version = strings.TrimPrefix(tag, "v")
	}
	if tag == "" {
		tag = "v" + version
	}

	relDate := *dateFlag
	if relDate == "" {
		relDate = time.Now().UTC().Format("2006-01-02")
	}

	hashes, err := loadPackageHashes(*sumsFlag)
	if err != nil {
		fmt.Fprintf(os.Stderr, "error loading checksums from %s: %v\n", *sumsFlag, err)
		os.Exit(1)
	}

	if *validateFlag {
		if err := validateManifests(*outDirFlag, *syncRootFlag, version, tag, *repoFlag, hashes); err != nil {
			fmt.Fprintf(os.Stderr, "validation failed: %v\n", err)
			os.Exit(1)
		}
		fmt.Println("All package manager manifests are valid and match SHA256SUMS.txt.")
		return
	}

	if err := generateAllManifests(*outDirFlag, *syncRootFlag, version, tag, *repoFlag, *homepageFlag, relDate, hashes); err != nil {
		fmt.Fprintf(os.Stderr, "error generating manifests: %v\n", err)
		os.Exit(1)
	}

	// Validate after generation
	if err := validateManifests(*outDirFlag, *syncRootFlag, version, tag, *repoFlag, hashes); err != nil {
		fmt.Fprintf(os.Stderr, "post-generation validation failed: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated and validated package manager manifests for %s (tag %s).\n", version, tag)
}

func loadPackageHashes(sumsPath string) (PackageHashes, error) {
	file, err := os.Open(sumsPath)
	if err != nil {
		return PackageHashes{}, err
	}
	defer file.Close()

	var hashes PackageHashes
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		hash := strings.ToLower(fields[0])
		if len(hash) != 64 {
			continue
		}
		name := strings.TrimPrefix(strings.Join(fields[1:], " "), "*")
		name = strings.TrimSpace(name)

		switch name {
		case "sendbeam-cli-darwin-arm64.tar.gz":
			hashes.DarwinArm64 = hash
		case "sendbeam-cli-darwin-amd64.tar.gz":
			hashes.DarwinAmd64 = hash
		case "sendbeam-cli-linux-arm64.tar.gz":
			hashes.LinuxArm64 = hash
		case "sendbeam-cli-linux-amd64.tar.gz":
			hashes.LinuxAmd64 = hash
		case "sendbeam-cli-windows-arm64.zip":
			hashes.WindowsArm64 = hash
		case "sendbeam-cli-windows-amd64.zip":
			hashes.WindowsAmd64 = hash
		}
	}

	if err := scanner.Err(); err != nil {
		return PackageHashes{}, err
	}

	var missing []string
	if hashes.DarwinArm64 == "" {
		missing = append(missing, "sendbeam-cli-darwin-arm64.tar.gz")
	}
	if hashes.DarwinAmd64 == "" {
		missing = append(missing, "sendbeam-cli-darwin-amd64.tar.gz")
	}
	if hashes.LinuxArm64 == "" {
		missing = append(missing, "sendbeam-cli-linux-arm64.tar.gz")
	}
	if hashes.LinuxAmd64 == "" {
		missing = append(missing, "sendbeam-cli-linux-amd64.tar.gz")
	}
	if hashes.WindowsArm64 == "" {
		missing = append(missing, "sendbeam-cli-windows-arm64.zip")
	}
	if hashes.WindowsAmd64 == "" {
		missing = append(missing, "sendbeam-cli-windows-amd64.zip")
	}

	if len(missing) > 0 {
		return hashes, fmt.Errorf("missing hashes in %s for: %s", sumsPath, strings.Join(missing, ", "))
	}

	return hashes, nil
}

func generateHomebrewFormula(version, tag, repo, homepage string, hashes PackageHashes) string {
	return fmt.Sprintf(`# typed: false
# frozen_string_literal: true

# This file was generated by SendBeam Package Automation. DO NOT EDIT.
class Sendbeam < Formula
  desc "Secure, direct, peer-to-peer file transfer in your browser and terminal"
  homepage "%s"
  version "%s"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "https://github.com/%s/releases/download/%s/sendbeam-cli-darwin-arm64.tar.gz"
      sha256 "%s"
    else
      url "https://github.com/%s/releases/download/%s/sendbeam-cli-darwin-amd64.tar.gz"
      sha256 "%s"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "https://github.com/%s/releases/download/%s/sendbeam-cli-linux-arm64.tar.gz"
      sha256 "%s"
    else
      url "https://github.com/%s/releases/download/%s/sendbeam-cli-linux-amd64.tar.gz"
      sha256 "%s"
    end
  end

  def install
    bin.install "sendbeam"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/sendbeam --version")
  end
end
`, homepage, version, repo, tag, hashes.DarwinArm64, repo, tag, hashes.DarwinAmd64, repo, tag, hashes.LinuxArm64, repo, tag, hashes.LinuxAmd64)
}

func generateScoopManifest(version, tag, repo, homepage string, hashes PackageHashes) (string, error) {
	manifest := map[string]interface{}{
		"version":     version,
		"description": "Secure, direct, peer-to-peer file transfer in your browser and terminal",
		"homepage":    homepage,
		"license":     "MIT",
		"architecture": map[string]interface{}{
			"64bit": map[string]string{
				"url":  fmt.Sprintf("https://github.com/%s/releases/download/%s/sendbeam-cli-windows-amd64.zip", repo, tag),
				"hash": hashes.WindowsAmd64,
			},
			"arm64": map[string]string{
				"url":  fmt.Sprintf("https://github.com/%s/releases/download/%s/sendbeam-cli-windows-arm64.zip", repo, tag),
				"hash": hashes.WindowsArm64,
			},
		},
		"bin":      "sendbeam.exe",
		"checkver": "github",
		"autoupdate": map[string]interface{}{
			"architecture": map[string]interface{}{
				"64bit": map[string]string{
					"url": fmt.Sprintf("https://github.com/%s/releases/download/v$version/sendbeam-cli-windows-amd64.zip", repo),
				},
				"arm64": map[string]string{
					"url": fmt.Sprintf("https://github.com/%s/releases/download/v$version/sendbeam-cli-windows-arm64.zip", repo),
				},
			},
			"hash": map[string]string{
				"url":   fmt.Sprintf("https://github.com/%s/releases/download/v$version/SHA256SUMS.txt", repo),
				"regex": "$sha256\\s+\\*?$basename",
			},
		},
	}

	buf := new(bytes.Buffer)
	enc := json.NewEncoder(buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "    ")
	if err := enc.Encode(manifest); err != nil {
		return "", err
	}
	return buf.String(), nil
}

